// Плоский поиск пояснения по слову (регистронезависимо) — для тултипов.
const BY_WORD = new Map<string, string>(
  GLOSSARY.flatMap((group) => group.terms).map((term) => [term.word.toLowerCase(), term.gloss]),
);

export function lookupGloss(word: string): string | undefined {
  return BY_WORD.get(word.toLowerCase());
}
