/** Стабильно-случайный выбор из пула по «семени» ситуации (без фликера). */
export function pickLine(pool: string[], seed: string): string {
  if (pool.length === 0) return "";
  let h = 0;
  for (let i = 0; i < seed.length; i++) {
    h = (h * 31 + seed.charCodeAt(i)) | 0;
  }
  return pool[Math.abs(h) % pool.length] ?? pool[0]!;
}
